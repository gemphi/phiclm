//! The O-code's ops on the ladder, and the tree's operator spellings: the
//! rung each dyadic operator stands on, shared by tokens and nodes.

use super::S;

/// Our OCODE ops, placed on the ladder — the first rung of the mapping.
impl From<&crate::ocode::Op> for S {
    fn from(op: &crate::ocode::Op) -> Self {
        use crate::ocode::Op;
        match op {
            Op::Num(_) => S::Ln,
            Op::Str(_) => S::Lstr,
            Op::Table(_) => S::Table,
            Op::Lp(_) => S::Lp,
            Op::Sp(_) => S::Sp,
            Op::Llp(_) => S::Llp,
            Op::Lg(_) => S::Lg,
            Op::Sg(_) => S::Sg,
            Op::Rv => S::Rv,
            Op::Stind => S::Stind,
            Op::Pop => S::Stack,
            Op::Neg => S::Neg,
            Op::Not => S::Not,
            Op::Abs => S::Abs,
            Op::Add => S::Add,
            Op::Sub => S::Sub,
            Op::Mul => S::Mul,
            Op::Div => S::Div,
            Op::Rem => S::Rem,
            Op::And => S::Logand,
            Op::Or => S::Logor,
            Op::Lsh => S::Lshift,
            Op::Rsh => S::Rshift,
            Op::Eqv => S::Eqv,
            Op::Neqv => S::Neqv,
            Op::Getbyte => S::Getbyte,
            Op::Putbyte => S::Putbyte,
            Op::Eq => S::Eq,
            Op::Ne => S::Ne,
            Op::Ls => S::Ls,
            Op::Gr => S::Gr,
            Op::Le => S::Le,
            Op::Ge => S::Ge,
            Op::Jump(_) => S::Jump,
            Op::Jf(_) => S::Jf,
            Op::Jt(_) => S::Jt,
            Op::Call { .. } => S::Fnap,
            Op::Fnrn => S::Fnrn,
            Op::Rtrn => S::Rtrn,
            Op::Finish => S::Finish,
            Op::Float => S::Float,
            Op::Fix => S::Fix,
            Op::Fneg => S::Fneg,
            Op::Fabs => S::Fabs,
            Op::Fadd => S::Fadd,
            Op::Fsub => S::Fsub,
            Op::Fmul => S::Fmul,
            Op::Fdiv => S::Fdiv,
            Op::Feq => S::Feq,
            Op::Fne => S::Fne,
            Op::Fls => S::Fls,
            Op::Fgr => S::Fgr,
            Op::Fle => S::Fle,
            Op::Fge => S::Fge,
            Op::Goto => S::Goto,
        }
    }
}

/// A dyadic operator's rung, by its canonical spelling in the tree.
pub(super) fn dyad(op: &str) -> S {
    match op {
        "!" => S::Vecap,
        "%" => S::Byteap,
        "*" => S::Mul,
        "/" => S::Div,
        "rem" => S::Rem,
        "+" => S::Add,
        "-" => S::Sub,
        "=" => S::Eq,
        "~=" => S::Ne,
        "<" => S::Ls,
        ">" => S::Gr,
        "<=" => S::Le,
        ">=" => S::Ge,
        "<<" => S::Lshift,
        ">>" => S::Rshift,
        "&" => S::Logand,
        "|" => S::Logor,
        "eqv" => S::Eqv,
        "neqv" => S::Neqv,
        "of" => S::Of,
        "#*" => S::Fmul,
        "#/" => S::Fdiv,
        "#+" => S::Fadd,
        "#-" => S::Fsub,
        "#=" => S::Feq,
        "#~=" => S::Fne,
        "#<" => S::Fls,
        "#>" => S::Fgr,
        "#<=" => S::Fle,
        "#>=" => S::Fge,
        _ => S::None,
    }
}
