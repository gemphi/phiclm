//! Every token's rung: the keywords as `declsyswords` numbers them, the
//! punctuation as the lexer's `token :=` does.

use super::ops::dyad;
use super::S;

impl crate::token::Token {
    /// The token's rung: `declsyswords` for a keyword (`bcplfe.b:1040-1105`,
    /// so `THEN` is `s_do`, `OR` is `s_else`, `XOR` is `s_neqv`, `MOD` is
    /// `s_rem`), the lexer's `token :=` for punctuation.
    pub fn kind(&self) -> S {
        use crate::token::Token;
        match self {
            Token::Num(_) | Token::Chr(_) => S::Number,
            Token::Fnum(_) => S::Fnum,
            Token::Name(_) => S::Name,
            Token::Str(_) => S::String,
            Token::Sep => S::Semicolon,
            Token::Key(k) => match *k {
                "and" => S::And,
                "abs" => S::Abs,
                "be" => S::Be,
                "bitsperbcplword" => S::Bitsperbcplword,
                "break" => S::Break,
                "by" => S::By,
                "case" => S::Case,
                "do" | "then" => S::Do,
                "default" => S::Default,
                "eq" => S::Eq,
                "eqv" => S::Eqv,
                "else" | "or" => S::Else,
                "endcase" => S::Endcase,
                "false" => S::False,
                "finish" => S::Finish,
                "fix" => S::Fix,
                "float" => S::Float,
                "for" => S::For,
                "goto" => S::Goto,
                "ge" => S::Ge,
                "gr" => S::Gr,
                "global" => S::Global,
                "get" => S::Get,
                "if" => S::If,
                "into" => S::Into,
                "let" => S::Let,
                "lv" => S::Lv,
                "le" => S::Le,
                "ls" => S::Ls,
                "logor" => S::Logor,
                "logand" => S::Logand,
                "loop" => S::Loop,
                "lshift" => S::Lshift,
                "manifest" => S::Manifest,
                "mod" | "rem" => S::Rem,
                "ne" => S::Ne,
                "needs" => S::Needs,
                "neqv" | "xor" => S::Neqv,
                "not" => S::Not,
                "of" => S::Of,
                "resultis" => S::Resultis,
                "return" => S::Return,
                "rshift" => S::Rshift,
                "rv" => S::Rv,
                "repeat" => S::Repeat,
                "repeatwhile" => S::Repeatwhile,
                "repeatuntil" => S::Repeatuntil,
                "section" => S::Section,
                "slct" => S::Slct,
                "static" => S::Static,
                "switchon" => S::Switchon,
                "to" => S::To,
                "test" => S::Test,
                "true" => S::True,
                "table" => S::Table,
                "unless" => S::Unless,
                "until" => S::Until,
                "vec" => S::Vec,
                "valof" => S::Valof,
                "while" => S::While,
                "writef" | "writes" => S::Name,
                _ => S::None,
            },
            Token::Pun(p) => match *p {
                "$(" | "{" => S::Lsect,
                "$)" | "}" => S::Rsect,
                ":=" => S::Ass,
                "->" => S::Cond,
                "(" => S::Lparen,
                ")" => S::Rparen,
                "[" => S::Sbra,
                "]" => S::Sket,
                "#abs" => S::Fabs,
                "#(" => S::Mthap,
                "," => S::Comma,
                "@" => S::Lv,
                "~" => S::Not,
                "?" => S::Query,
                ":" => S::Colon,
                other => dyad(other),
            },
        }
    }
}
